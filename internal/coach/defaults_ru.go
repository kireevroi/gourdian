// translate applies another language's wording to a rule that ships with the trainer.
func translate(spec RuleSpec, lang string) RuleSpec {
	if lang != "ru" {
		return spec
	}
	w, ok := russian[spec.ID]
	if !ok {
		return spec
	}
	if w.Name != "" {
		spec.Name = w.Name
	}
	if w.Text != "" {
		spec.Then.Text = w.Text
	}
	if w.Speech != "" {
		spec.Then.Speech = w.Speech
	}
	if w.Advice != "" {
		spec.Then.Advice = w.Advice
	}
	if w.Habit != "" {
		spec.Then.Habit = w.Habit
	}
	return spec
}
